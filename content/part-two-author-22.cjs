const assert = require('node:assert/strict');

const groups = [];
const add = (number, page, cases, make) => {
  assert.equal(cases.length, 3);
  groups.push({
    prototypeId: `22.${number}`,
    examNumber: 22,
    sourcePage: page,
    analogs: cases.map((parameters, index) => ({
      id: `22.${number}-${'abc'[index]}`,
      requiresGraph: true,
      graphSpec: { kind: number, parameters },
      ...make(parameters),
    })),
  });
};

add(1, 115, [
  { lineShift: 0, answer: '(0; 1]' },
  { lineShift: 1, answer: '{0} ∪ {1}' },
  { lineShift: 2, answer: '{0} ∪ (1; 2)' },
], ({ lineShift, answer }) => ({
  prompt: `Постройте график: y = (x − 1)² при x ≥ 0; y = x + ${lineShift} при x < 0. При каких m прямая y = m пересекает график ровно в двух точках?`,
  answer,
  solution: `Правая ветвь параболы даёт одну точку при m = 0 и при m > 1, две — при 0 < m ≤ 1. Левая прямая добавляет одну точку при m < ${lineShift}. Суммируя количества пересечений, получаем ${answer}.`,
  validationMode: 'interval',
}));

add(2, 115, [
  { vertexX: 1, numerator: 1 },
  { vertexX: 2, numerator: 4 },
  { vertexX: 3, numerator: 9 },
], ({ vertexX, numerator }) => ({
  prompt: `Постройте график: y = (x − ${vertexX})² при x ≥ 0; y = −${numerator}/x при x < 0. При каких m горизонтальная прямая y = m имеет с графиком одну или две общие точки?`,
  answer: `{0} ∪ (${vertexX ** 2}; +∞)`,
  solution: `Гиперболическая ветвь даёт одну точку для каждого m > 0. Парабола даёт одну точку при m = 0, две при 0 < m ≤ ${vertexX ** 2} и одну при m > ${vertexX ** 2}. Следовательно, нужные уровни: m = 0 либо m > ${vertexX ** 2}.`,
  validationMode: 'interval',
}));

add(3, 115, [1, 2, 3], (shift) => ({
  prompt: `Постройте график: y = x² + ${shift} при x ≥ −1; y = −${shift}/x при x < −1. Найдите все m, при которых y = m имеет с графиком ровно одну общую точку.`,
  answer: `(0; ${shift}] ∪ (${shift + 1}; +∞)`,
  solution: `Ветвь гиперболы принимает уровни 0 < m < ${shift} по одному разу. Парабола даёт одну точку при m = ${shift}, две при ${shift} < m ≤ ${shift + 1}, затем одну при m > ${shift + 1}. Поэтому ответ: (0; ${shift}] ∪ (${shift + 1}; +∞).`,
  validationMode: 'interval',
}));

